import { PGlite } from '@electric-sql/pglite';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
// Only platform-owned schemas are stubbed. Every public contract comes from migrations.
const bootstrap = readFileSync(new URL('./schema-platform-fixture.sql', import.meta.url), 'utf8');
const db = new PGlite();
const directory = new URL('../supabase/migrations/', import.meta.url);
const migrations = readdirSync(directory).filter(name => name.endsWith('.sql')).sort();
const digest = createHash('sha256');
const q = name => JSON.stringify(name);
const scalar = type => {
  if (type.endsWith('[]')) return `(${scalar(type.slice(0, -2))})[]`;
  if (['json', 'jsonb'].includes(type)) return 'Json';
  if (['boolean', 'bool'].includes(type)) return 'boolean';
  if (/^(smallint|integer|bigint|int[248]|real|double precision|numeric|decimal|float[48])(?:\(|$)/.test(type)) return 'number';
  if (type === 'void') return 'undefined';
  if (/^(text|uuid|varchar|character|timestamp|date|time|name)/.test(type)) return 'string';
  throw new Error(`Unsupported PostgreSQL type: ${type}`);
};
let out = '';
try {
  await db.exec(bootstrap);
  for (const name of migrations) {
    const sql = readFileSync(new URL(name, directory), 'utf8');
    digest.update(name + '\n' + sql);
    await db.exec('BEGIN;\n' + sql + '\nCOMMIT;');
  }
  out = `// Generated by npm run db:types from all public-schema migrations. Do not edit.\n// Migration SHA256: ${digest.digest('hex')}\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport interface Database { public: { Tables: {\n`;
  const tables = (await db.query("select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' order by table_name")).rows;
  for (const { table_name: table } of tables) {
    const cols = (await db.query(`select column_name, is_nullable, column_default, is_generated, udt_name,
      format_type(a.atttypid, a.atttypmod) as sql_type
      from information_schema.columns c join pg_class cl on cl.relname=c.table_name
      join pg_namespace n on n.oid=cl.relnamespace and n.nspname=c.table_schema
      join pg_attribute a on a.attrelid=cl.oid and a.attname=c.column_name
      where c.table_schema='public' and c.table_name=$1 order by c.ordinal_position`, [table])).rows;
    out += `${q(table)}: {\n`;
    for (const mode of ['Row', 'Insert', 'Update']) {
      out += `${mode}: {\n`;
      for (const col of cols) {
        if (mode !== 'Row' && col.is_generated === 'ALWAYS') { out += `${q(col.column_name)}?: never;\n`; continue; }
        const optional = mode === 'Update' || (mode === 'Insert' && (col.column_default !== null || col.is_nullable === 'YES'));
        out += `${q(col.column_name)}${optional ? '?' : ''}: ${scalar(col.sql_type)}${col.is_nullable === 'YES' ? ' | null' : ''};\n`;
      }
      out += '};\n';
    }
    const relations = (await db.query(`select con.conname as name, target.relname as target,
      array(select attname from unnest(con.conkey) with ordinality k(num,ord) join pg_attribute a on a.attrelid=con.conrelid and a.attnum=k.num order by ord) as columns,
      array(select attname from unnest(con.confkey) with ordinality k(num,ord) join pg_attribute a on a.attrelid=con.confrelid and a.attnum=k.num order by ord) as refs
      from pg_constraint con join pg_class source on source.oid=con.conrelid join pg_class target on target.oid=con.confrelid
      join pg_namespace n on n.oid=target.relnamespace
      where con.contype='f' and source.relname=$1 and n.nspname='public' order by con.conname`, [table])).rows;
    out += 'Relationships: [' + relations.map(rel => `{foreignKeyName:${q(rel.name)};columns:${JSON.stringify(rel.columns)};isOneToOne:false;referencedRelation:${q(rel.target)};referencedColumns:${JSON.stringify(rel.refs)}}`).join(',') + '];\n};\n';
  }
  out += '}; Views: { [key in never]: never }; Functions: {\n';
  const funcs = (await db.query(`select p.oid, p.proname as name, p.proargnames as names, p.proargmodes as modes,
    p.pronargdefaults as defaults, p.proretset as is_set, format_type(p.prorettype,null) as return_type,
    array(select format_type(t,null) from unnest(coalesce(p.proallargtypes,p.proargtypes::oid[])) t) as types
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.prorettype <> 'trigger'::regtype order by p.proname`)).rows;
  for (const fn of funcs) {
    const modes = fn.modes || fn.types.map(() => 'i');
    const inputs = modes.map((m,i) => ({m,i})).filter(x => ['i','b','v'].includes(x.m));
    const outputs = modes.map((m,i) => ({m,i})).filter(x => ['o','b','t'].includes(x.m));
    const args = inputs.map(({i}, index) => `${q(fn.names?.[i] || `arg${i}`)}${index >= inputs.length-fn.defaults ? '?' : ''}: ${scalar(fn.types[i])}`).join(';');
    let returns;
    if (outputs.length) returns = '{' + outputs.map(({i}) => `${q(fn.names[i])}: ${scalar(fn.types[i])} | null`).join(';') + '}';
    else if (tables.some(t => t.table_name === fn.return_type)) returns = `Database['public']['Tables'][${q(fn.return_type)}]['Row']`;
    else returns = scalar(fn.return_type);
    out += `${q(fn.name)}: { Args: ${inputs.length ? '{'+args+'}' : 'Record<string, never>'}; Returns: ${returns}${fn.is_set ? '[]' : ''} };\n`;
  }
  out += '}; Enums: { [key in never]: never }; CompositeTypes: { [key in never]: never } } }\n';
} finally { await db.close(); }
const target = new URL('../src/infrastructure/supabase/database.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) throw new Error('Database types are stale. Run npm run db:types.');
  console.log('Generated database contract matches migrated schema.');
} else { writeFileSync(target, out); console.log('Generated public database contract.'); }
